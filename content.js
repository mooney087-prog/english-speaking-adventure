export function stageProgress(events, stage) {
 const has=(kind,index)=>events.some(e=>e.stage===stage&&e.kind===kind&&e.item===index);
 const count=(kind,n)=>Array.from({length:n},(_,i)=>has(kind,i)).filter(Boolean).length;
 const heard=count('listen_word',10), words=count('record_word',10);
 const heardSentences=count('listen_sentence',5), sentences=count('record_sentence',5);
 return {heard,words,sentences,score:heard+words+heardSentences+sentences,done:heard===10&&words===10&&heardSentences===5&&sentences===5};
}
